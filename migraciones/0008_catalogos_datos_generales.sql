ALTER TABLE patrimonial.funcionario_datos
  ADD COLUMN IF NOT EXISTS estado_civil_id      smallint REFERENCES catalogos.estado_civil (id),
  ADD COLUMN IF NOT EXISTS pais_nacimiento_id   smallint REFERENCES catalogos.pais (id),
  ADD COLUMN IF NOT EXISTS nacionalidad_id      smallint REFERENCES catalogos.nacionalidad (id),
  ADD COLUMN IF NOT EXISTS lada_celular_id      smallint REFERENCES catalogos.prefijo_telefonico (id),
